const fs = require('fs');
const path = require('path');
const { startStack, openPage, intoGame, sleep } = require('./e2e.cjs');

const HEROES = [['kafka', 'blade', 'seele'], ['clara', 'bronya', 'luocha']];

async function dress(p, i) {
  await p.ev(`(() => {
    const g = hsrui.game;
    g.state.flags.express_intro = true;
    g.state.name = ${JSON.stringify(['Kaia', 'Finlay'][i])};
    for (const id of ${JSON.stringify(HEROES[i])}) if (Hsr98.CHARS[id]) g.addChar(id, ${40 + i * 15});
    const pr = g.profile();
    pr.sign = ${JSON.stringify(['Pink Lavender', ''][i])};
    pr.show = ${JSON.stringify(HEROES[i])};
    pr.comp = ['trail'];
    pr.avatar = ${JSON.stringify(HEROES[i][0])};
    pr.stage = ${JSON.stringify(HEROES[i][1])};
    g.state.tl.lvl = ${65 + i * 5};
    g.script = null;
    g.pending = null;
    hsrui.screens = [];
    return 1;
  })()`);
}

async function main() {
  const shots = (process.argv.find(a => a.startsWith('--shots=')) || '').slice(8) || path.join(__dirname, '..', '..', 'dist', 'friends-shots');
  fs.mkdirSync(shots, { recursive: true });
  const stack = await startStack({ speed: 1 });
  const report = { steps: [], ok: false };
  const log = t => { report.steps.push(t); console.log(t); };
  const pages = [];
  try {
    for (let i = 0; i < 2; i++) { pages.push(await openPage(stack.api, stack.base + '/hsr98.html', ['A', 'B'][i])); await intoGame(pages[i], i, stack.netUrl); await dress(pages[i], i); }
    const [a, b] = pages;
    const shot = async (p, name) => { await sleep(120); await p.shot(path.join(shots, 'friends-' + name + '.png')); };
    await a.ev('hsrui.openFriends(0);1');
    await a.until('!!hsrui.top().netConsent', 'consent');
    await shot(a, '01-consent');
    await a.key('ArrowLeft');
    await a.key('Enter');
    await a.until('!!hsrui.top().friends', 'the friends screen');
    await a.ev('Net98.state="connecting";1');
    await shot(a, '02-connecting');
    await a.until('Net98.state==="online"||true', 'state');
    await a.ev('Net98.disconnect("off");Net98.connect();1');
    await a.until('Net98.state==="online"&&!!Net98.friends', 'A online');
    await shot(a, '03-empty');
    await b.ev('hsrui.openFriends(0);1');
    await b.key('ArrowLeft');
    await b.key('Enter');
    await b.until('Net98.state==="online"&&!!Net98.friends', 'B online');
    await sleep(2500);
    const uidA = await a.ev('Net98.uid()'), uidB = await b.ev('Net98.uid()');
    log('uids ' + uidA + ' ' + uidB);
    await a.key('KeyE');
    await shot(a, '04-add');
    await a.ev('hsrui.top().addSel=1;1');
    await a.key('Enter');
    await a.until('!!hsrui.top().textEntry', 'uid entry');
    await a.ev('window.__pastes=0;document.addEventListener("paste",()=>{window.__pastes++;});1');
    for (const type of ['rawKeyDown', 'keyUp']) await a.send('Input.dispatchKeyEvent', { type, modifiers: 2, windowsVirtualKeyCode: 86, code: 'KeyV', key: 'v' });
    await a.until('window.__pastes===1', 'a real Ctrl+V', 5000);
    log('real Ctrl+V reached the game');
    const pasteEvent = text => a.ev('(()=>{const box=new DataTransfer();box.setData("text/plain",' + JSON.stringify(text) + ');document.body.dispatchEvent(new ClipboardEvent("paste",{clipboardData:box,bubbles:true,cancelable:true}));return 1;})()');
    await a.ev('hsrui.top().value="";hsrui.top().note=null;1');
    await pasteEvent('в буфере нет номера');
    if (await a.ev('hsrui.top().value!==""||hsrui.top().note.text!=="В буфере обмена нет UID."')) throw new Error('a paste without a UID');
    await shot(a, '05a-uid-miss');
    await a.ev('Object.defineProperty(navigator.clipboard,"readText",{configurable:true,value:()=>Promise.resolve(' + JSON.stringify('Мой UID ' + uidB) + ')});1');
    const at = await a.ev('(()=>{const r=hsrui.canvas.getBoundingClientRect();return {x:r.left+(130+22+132+42)*r.width/640,y:r.top+(70+84+48+6+14)*r.height/480};})()');
    for (const type of ['mousePressed', 'mouseReleased']) await a.send('Input.dispatchMouseEvent', { type, x: at.x, y: at.y, button: 'left', clickCount: 1 });
    await a.until('hsrui.top().value===' + JSON.stringify(uidB), 'the paste button');
    log('paste button filled the UID');
    await shot(a, '05-uid-entry');
    await a.ev('hsrui.top().value="";1');
    await pasteEvent('Мой UID: ' + uidB + ', жду');
    if (await a.ev('hsrui.top().value!==' + JSON.stringify(uidB))) throw new Error('the paste event');
    log('paste event filled the UID');
    await a.key('Enter');
    await a.until('!!Net98.found', 'found');
    await shot(a, '06-found');
    if (!(await a.ev('Net98.found.ok&&Net98.found.rel==="none"&&Net98.found.open'))) throw new Error('find failed');
    await a.ev('hsrui.top().addSel=2;1');
    await a.key('Enter');
    await b.until('Net98.friends.in.length===1', 'B sees the request');
    log('request reached B');
    await shot(b, '07-b-list-with-request');
    await b.key('KeyR');
    await b.until('!!hsrui.top().friendRequests', 'requests');
    await shot(b, '08-requests');
    await b.key('Enter');
    await b.until('Net98.friends.list.length===1', 'B has a friend');
    await a.until('Net98.friends.list.length===1', 'A has a friend');
    log('accepted');
    await b.key('Escape');
    await a.key('KeyE');
    await a.ev('hsrui.top().sel=1;1');
    await a.until('Net98.friends.list[0].name==="Finlay"&&Net98.friends.list[0].show.length===3', 'the card of B');
    await shot(a, '09-a-list-friend');
    await b.ev('hsrui.game.script=null;hsrui.game.pending=null;hsrui.screens=[];1');
    await a.until('JSON.stringify(Net98.friends.list[0].status)!=="null"', 'a status');
    const st1 = await a.ev('JSON.stringify(Net98.friends.list[0].status)');
    await b.ev('hsrui.mode="battle";1');
    await a.until('Net98.friends.list[0].status&&Net98.friends.list[0].status.c==="battle"', 'status change');
    await shot(a, '10-a-status-battle');
    await b.ev('hsrui.mode="field";1');
    log('status ' + st1 + ' then battle');
    await a.key('KeyF');
    await a.until('Net98.friends.list[0].fav', 'favourite');
    await shot(a, '11-a-favourite');
    await a.key('KeyO');
    await a.key('KeyV');
    await a.until('!!hsrui.top().friendProfile', 'profile');
    await a.until('!!Net98.cards[' + JSON.stringify(uidB) + ']', 'the full card');
    await shot(a, '12-profile-chars');
    await a.key('KeyQ');
    await shot(a, '13-profile-rec');
    await a.key('KeyE');
    await a.key('KeyE');
    await shot(a, '14-profile-coll');
    await a.key('Escape');
    await a.ev('hsrui.top().sel=0;1');
    await a.key('KeyV');
    await a.until('!!hsrui.top().friendProfile', 'solo profile');
    await shot(a, '15-profile-solo');
    await a.key('Escape');
    await a.ev('hsrui.top().sel=1;1');
    await a.key('Enter');
    await a.until('!!hsrui.top().friendMenu', 'menu');
    await shot(a, '16-menu');
    await a.key('Escape');
    await a.ev('hsrui.openHdHub();hsrui.openHdTable();1');
    await a.key('Enter');
    await a.until('!!Net98.table', 'a table');
    await a.ev('hsrui.openFriends(0);hsrui.top().sel=1;1');
    await a.key('Enter');
    await a.until('!!hsrui.top().friendMenu', 'menu at the table');
    await a.ev('hsrui.top().sel=hsrui.top().items().findIndex(it=>it.id==="invite");1');
    await a.key('Enter');
    await b.until('Net98.activeInvites().length===1', 'the invite');
    await b.ev('hsrui.game.script=null;hsrui.game.pending=null;hsrui.screens=[];hsrui.update(0.3);1');
    await sleep(400);
    await shot(b, '17-b-invite-notice');
    await b.ev('hsrui.game.script=null;hsrui.game.pending=null;hsrui.openFriends(0);1');
    await shot(b, '18-b-invite-strip');
    await b.key('KeyY');
    await b.until('!!Net98.table&&Net98.table.seats.filter(Boolean).length===2', 'B at the table');
    log('invite led to the table');
    await shot(b, '19-b-at-table');
    await b.ev('Net98.send("tableLeave");hsrui.screens=[];hsrui.openFriends(0);hsrui.top().sel=1;1');
    await a.ev('Net98.send("tableLeave");hsrui.screens=[];hsrui.openFriends(0);hsrui.top().sel=1;1');
    await a.until('!Net98.table', 'A left the table');
    await a.key('Enter');
    await a.until('!!hsrui.top().friendMenu', 'menu to block');
    await a.ev('hsrui.top().sel=hsrui.top().items().findIndex(it=>it.id==="block");1');
    await a.key('Enter');
    await a.key('Enter');
    await a.until('Net98.friends.blocks.length===1&&Net98.friends.list.length===0', 'blocked');
    await b.until('Net98.friends.list.length===0', 'the block reached B');
    log('blocked');
    await a.key('KeyB');
    await a.until('!!hsrui.top().friendBlocks', 'blocks');
    await shot(a, '20-blocks');
    await a.key('Enter');
    await a.until('Net98.friends.blocks.length===0', 'unblocked');
    await a.key('Escape');
    log('unblocked');
    await a.ev('Net98.found=null;Net98.send("req",{uid:' + JSON.stringify(uidB) + '});1');
    await b.until('Net98.friends.in.length===1', 'a second request');
    await b.ev('Net98.send("answer",{uid:' + JSON.stringify(uidA) + ',yes:true});1');
    await a.until('Net98.friends.list.length===1', 'friends again');
    await a.ev('hsrui.top().sel=1;1');
    await a.key('Enter');
    await a.until('!!hsrui.top().friendMenu', 'menu to remove');
    await a.ev('hsrui.top().sel=hsrui.top().items().findIndex(it=>it.id==="del");1');
    await a.key('Enter');
    await a.key('Enter');
    await a.until('Net98.friends.list.length===0', 'removed');
    await b.until('Net98.friends.list.length===0', 'removed on the other side');
    log('removed');
    await a.ev('hsrui.top().tab=1;1');
    await shot(a, '21-add-recent');
    await a.ev('hsrui.top().tab=0;hsrui.openNetSettings();1');
    await shot(a, '22-settings');
    await a.ev('hsrui.screens=[];hsrui.openMenu();1');
    await shot(a, '23-phone-rail');
    await a.ev('hsrui.screens=[];hsrui.openPhoneMenu();1');
    await shot(a, '24-phone-menu');
    await a.ev('hsrui.screens=[];hsrui.openFriends(0);window.__keep=Net98.state;1');
    for (const state of ['offline', 'modem', 'outdated', 'replaced', 'banned', 'off', 'denied']) {
      await a.ev('Net98.disconnect("off");Net98.state=' + JSON.stringify(state) + ';1');
      await shot(a, '30-state-' + state);
    }
    report.errors = pages.flatMap(p => p.errors.map(e => p.name + ': ' + e));
    report.ok = !report.errors.length;
  } catch (err) {
    report.failure = String(err && err.stack || err);
    report.errors = pages.flatMap(p => p.errors.map(e => p.name + ': ' + e));
  }
  console.log(JSON.stringify(report, null, 1));
  await stack.stop();
  process.exit(report.ok ? 0 : 1);
}

if (require.main === module) main().catch(err => { console.error(err); process.exit(1); });
