  M.parse = id => {
    const def = M.DEFS[id];
    if (!def) throw new Error('no map ' + id);
    const h = def.rows.length, w = def.rows[0].length;
    if (def.rows.some(r => r.length !== w)) throw new Error(id + ': ragged rows');
    if (w > 96 || h > 64) throw new Error(id + ': map larger than 96x64');
    const tiles = new Uint8Array(w * h), objects = [], seen = new Set(), entries = {};
    let n = 0;
    def.rows.forEach((row, y) => {
      for (let x = 0; x < w; x++) {
        const ch = row[x];
        if (M.CHARS[ch]) { tiles[y * w + x] = M.T[M.CHARS[ch]]; continue; }
        tiles[y * w + x] = M.T.floor;
        if (ch === '@') { entries['@'] = [x, y]; continue; }
        if (M.GENERIC[ch]) { objects.push(Object.assign({ id: ch + (n++), letter: ch, x, y }, M.GENERIC[ch])); continue; }
        if (/[a-z]/.test(ch)) {
          if (seen.has(ch)) throw new Error(`${id}: letter ${ch} used twice`);
          seen.add(ch);
          const p = def.props[ch];
          if (!p) throw new Error(`${id}: no props for ${ch}`);
          objects.push(Object.assign({ id: ch, letter: ch, x, y }, JSON.parse(JSON.stringify(p))));
          continue;
        }
        throw new Error(`${id}: unknown map character ${ch}`);
      }
    });
    for (const k of Object.keys(def.props)) if (!seen.has(k)) throw new Error(`${id}: props ${k} not on the map`);
    const at = {};
    for (const [name, letter] of Object.entries(def.entries)) {
      const pos = letter === '@' ? entries['@'] : (objects.find(o => o.letter === letter) || {});
      if (!pos || pos.x === undefined && !Array.isArray(pos)) throw new Error(`${id}: entry ${name} has no place`);
      at[name] = Array.isArray(pos) ? pos : [pos.x, pos.y];
    }
    return { id, def, w, h, tiles, objects, entries: at };
  };
