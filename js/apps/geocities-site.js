  saveArtifactToVfs(resident, openNotepad = false) {
    if (!resident || !resident.artifactName) return false;
    try {
      const docsPath = ['My Computer', 'C:', 'My Documents'];
      if (typeof window !== 'undefined' && window.vfs) {
        if (typeof window.vfs.mkdir === 'function') {
          window.vfs.mkdir(docsPath);
        }
        if (typeof window.vfs.writeFile === 'function') {
          window.vfs.writeFile(docsPath, resident.artifactName, resident.artifactBody);
        } else if (typeof window.vfs.createFile === 'function') {
          window.vfs.createFile(docsPath, resident.artifactName, resident.artifactBody);
        }
      }
      if (openNotepad && typeof window !== 'undefined' && window.appNotepad) {
        if (typeof window.appNotepad.open === 'function') {
          window.appNotepad.open(resident.artifactName, resident.artifactBody, docsPath);
        } else if (typeof window.appNotepad.openWithContent === 'function') {
          window.appNotepad.openWithContent(resident.artifactName, resident.artifactBody, docsPath);
        }
      }
      this.lastStatusBySlug[resident.slug] = openNotepad
        ? `Файл ${resident.artifactName} сохранён в C:\\My Documents и открыт в Блокноте!`
        : `Файл ${resident.artifactName} успешно сохранён в папку C:\\My Documents!`;
      if (typeof window !== 'undefined' && window.soundSys && typeof window.soundSys.playDing === 'function') {
        window.soundSys.playDing();
      }
      return resident.artifactName;
    } catch (e) {
      return false;
    }
  }

