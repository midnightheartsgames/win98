  function factionUnits(factionId) {
    return UNIT_LIST.filter(u => u.faction === factionId).sort((a, b) => a.tier - b.tier);
  }

  function unitNameCount(unitId, count) {
    const u = UNITS[unitId];
    if (!u) return String(count);
    return count + ' ' + H.plural(count, u.names[0], u.names[1], u.names[2]);
  }

  function unitPower(unitId) {
    const u = UNITS[unitId];
    if (!u) return 1;
    const avgDmg = (u.dmg[0] + u.dmg[1]) * 0.5;
    let p = u.hp * (1 + u.def * 0.06) + avgDmg * 4 * (1 + u.atk * 0.08);
    if (u.doubleStrike || u.doubleShot) p *= 1.65;
    if (u.flying) p *= 1.25;
    if (u.ranged) p *= 1.25;
    if (u.noRetaliation) p *= 1.2;
    if (u.unlimitedRetaliation) p *= 1.2;
    if (u.allAroundAttack) p *= 1.35;
    if (u.twoHexBreath) p *= 1.25;
    if (u.magicImmune) p *= 1.35;
    if (u.elementalImmune) p *= 1.15;
    if (u.soulSteal) p *= 1.5;
    if (u.halveChance) p *= 1.4;
    if (u.regenerates) p *= 1.15;
    return Math.round(p);
  }

  function unitCostText(unitId, count) {
    const u = UNITS[unitId];
    if (!u) return '';
    const n = count === undefined ? 1 : count;
    const parts = [];
    for (const k of H.RES_ORDER) {
      if (u.cost[k]) {
        parts.push((u.cost[k] * n) + ' ' + H.RESOURCES[k].short.toLowerCase());
      }
    }
    return parts.join(', ');
  }

