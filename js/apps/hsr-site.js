    paintArt(cv) {
      const H = Hsr();
      if (!H || !H.Gfx) return;
      const G = H.Gfx;
      const [kind, id, arg] = cv.dataset.art.split(':');
      const g = cv.getContext('2d');
      if (!g) return;
      g.imageSmoothingEnabled = false;
      const fit = (src) => g.drawImage(src, 0, 0, cv.width, cv.height);
      if (kind === 'fig') fit(G.figureCanvas(G.lookOf(id, null), Number(arg) || 1));
      else if (kind === 'figf') fit(G.figureCanvas(G.trailLook('f'), Number(arg) || 1));
      else if (kind === 'bust') fit(G.bustCanvas(G.lookOf(id, null), Number(arg) || 64));
      else if (kind === 'path') G.pathIcon(g, id, 0, 0, cv.width, '#f3dc96');
      else if (kind === 'item') G.itemIcon(g, id, 0, 0, cv.width);
      else if (kind === 'foe') fit(G.foeCanvas(id, Number(arg) || 52, 0));
      else if (kind === 'still') H.Cine.still(g, id, cv.width, cv.height, 0, null);
      else if (kind === 'eid') fit(H.Eidolons.pic(id).colorD);
      else if (kind === 'title') this.startWindow(cv);
    },

    starTile() {
      if (this.tile !== undefined) return this.tile;
      this.tile = null;
      if (typeof document === 'undefined' || !document.createElement) return null;
      const cv = document.createElement('canvas');
      cv.width = 96;
      cv.height = 96;
      const g = cv.getContext && cv.getContext('2d');
      if (!g || !cv.toDataURL) return null;
      g.fillStyle = '#0b0f26';
      g.fillRect(0, 0, 96, 96);
      const colors = ['#4a5088', '#6a70a8', '#9aa0d0', '#f3dc96'];
      for (let i = 0; i < 26; i++) {
        g.fillStyle = colors[i % 7 === 0 ? 3 : i % 3];
        g.fillRect((i * 37 + 11) % 96, (i * 61 + 7) % 96, 1, 1);
      }
      this.tile = cv.toDataURL('image/png');
      return this.tile;
    },

    startWindow(cv) {
      const H = Hsr();
      if (!H || !H.TitleScene) return;
      const g = cv.getContext('2d');
      const t0 = (typeof performance !== 'undefined' ? performance.now() : Date.now()) - 4000;
      let last = 0;
      const step = (now) => {
        if (!cv.isConnected) return;
        if (now - last >= 80) {
          last = now;
          H.TitleScene.draw(g, cv.width, cv.height, (now - t0) / 1000);
        }
        this.anim = requestAnimationFrame(step);
      };
      H.TitleScene.draw(g, cv.width, cv.height, 4);
      const still = typeof matchMedia === 'function' && matchMedia('(prefers-reduced-motion: reduce)').matches;
      if (!still && typeof requestAnimationFrame === 'function') this.anim = requestAnimationFrame(step);
    },

    attachEvents(win, container, url) {
      const route = this.parseUrl(url);
      const gm = this.gm;
      if (this.anim && typeof cancelAnimationFrame === 'function') cancelAnimationFrame(this.anim);
      this.anim = null;
      if (route.view === 'home') this.countVisit();
      const page = container.querySelector('.hsrs-page');
      const tile = this.starTile();
      if (page && tile) page.style.backgroundImage = `url(${tile})`;

      container.querySelectorAll('canvas.hsrs-art').forEach(cv => {
        try { this.paintArt(cv); } catch (e) { console.warn('hsr site art', cv.dataset.art, e); }
      });

      container.querySelectorAll('input[name="hsrs-mirror"]').forEach(r => r.addEventListener('change', () => { this.mirror = r.value; }));

      container.querySelectorAll('[data-hsrs]').forEach(btn => btn.addEventListener('click', () => {
        if (window.soundSys && window.soundSys.playClick) window.soundSys.playClick();
        const act = btn.dataset.hsrs;
        if (act === 'download' || act === 'redownload') this.startDownload(this.mirror);
        else if (act === 'show-dl' && this.dl) window.winManager.bringToTop(this.dl.winId);
        else if (act === 'setup') this.openSetup();
        else if (act === 'play' && gm && gm.isInstalled(GAME)) gm.catalog[GAME].launch();
        else if (act === 'folder' && window.appExplorer) window.appExplorer.open(DOWNLOADS.slice());
        else if (act === 'steam' && gm) gm.showInSteam(GAME);
        else if (act === 'sign') this.sign(win, container, url);
      }));
    },

    sign(win, container, url) {
      const val = (sel) => { const el = container.querySelector(sel); return el ? el.value : ''; };
      const d = new Date();
      const date = `${String(d.getDate()).padStart(2, '0')}.${String(d.getMonth() + 1).padStart(2, '0')}.${d.getFullYear()}`;
      const entry = this.addGuestbookEntry(val('#hsrs-gb-name'), val('#hsrs-gb-city'), val('#hsrs-gb-text'), date);
      if (!entry) {
        const err = container.querySelector('#hsrs-gb-error');
        if (err) err.textContent = 'Напишите имя и сообщение.';
        return;
      }
      if (window.soundSys && window.soundSys.playDing) window.soundSys.playDing();
      if (window.appIE && window.appIE.renderPage) window.appIE.renderPage(win, url);
    },

    refresh() {
      const ie = window.appIE;
      if (!ie || !ie.currentWin || !ie.currentUrl || !window.winManager || !window.winManager.windows.has('app_ie')) return;
      if (ie.identifyPageKey(ie.currentUrl) === 'hsr') ie.renderPage(ie.currentWin, ie.currentUrl);
    },

    ensureDownloads() {
      const vfs = window.vfs;
      if (!vfs || !vfs.resolvePath) return null;
      let dir = vfs.resolvePath(DOWNLOADS);
      if (!dir) {
        const docs = vfs.resolvePath(DOWNLOADS.slice(0, -1));
        if (!docs || !docs.children) return null;
        docs.children.Downloads = { type: 'folder', name: 'Downloads', icon: 'folder-downloads', children: {} };
        dir = docs.children.Downloads;
      }
      return dir;
    },

    saveInstaller() {
      const dir = this.ensureDownloads();
      if (!dir) return false;
      dir.children[SETUP_EXE] = { type: 'executable', name: SETUP_EXE, icon: 'setup-installer', app: 'hsrsetup' };
      window.vfs.saveToStorage();
      const expWin = window.winManager.windows && window.winManager.windows.get('explorer');
      if (expWin && window.appExplorer && window.appExplorer.renderFolder) window.appExplorer.renderFolder(expWin);
      if (window.desktop) window.desktop.renderIcons();
      return true;
    },

    downloadSeconds(mirror) {
      return Math.min(30, Math.max(6, SETUP_KB / mirror.kbs / TIME_SCALE));
    },

