    const sam = g.actors.sam, max = g.actors.max;
    const y0 = sam.y, t0 = g.time;
    max.scripted = true;
    g.sfx('boing');
    while (g.time - t0 < dur && !g.skipping) {
      const k = (g.time - t0) / dur;
      sam.y = y0 - Math.sin(k * Math.PI) * height;
      yield null;
    }
    sam.y = y0;
    max.scripted = false;
