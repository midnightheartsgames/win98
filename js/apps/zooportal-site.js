  parseRoute(rawUrl = '') {
    const clean = String(rawUrl || this.baseUrl).trim();
    const qIndex = clean.indexOf('?');
    const queryStr = qIndex >= 0 ? clean.slice(qIndex + 1) : '';
    const params = {};
    if (queryStr) {
      queryStr.split('&').forEach(pair => {
        const [k, v] = pair.split('=');
        if (k) {
          try {
            params[decodeURIComponent(k)] = decodeURIComponent((v || '').replace(/\+/g, ' '));
          } catch (e) {
            params[k] = v || '';
          }
        }
      });
    }
    const noProto = clean.replace(/^https?:\/\/[^/]+/i, '');
    const pathPart = (noProto.split('?')[0] || '/').replace(/\/+$/, '') || '/';
    if (pathPart === '/atlas') return { page: 'atlas', params };
    if (pathPart === '/aquarium') return { page: 'aquarium', params };
    if (pathPart === '/expeditions') return { page: 'expeditions', params };
    if (pathPart === '/article') return { page: 'article', params };
    if (pathPart === '/vetclinic') return { page: 'vetclinic', params };
    if (pathPart === '/club') return { page: 'club', params };
    return { page: 'home', params };
  }

  encodeHtml(html) {
    if (this.encoding === 'win1251') return html;
    const mapTranslit = {
      'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'е': 'e', 'ё': 'yo', 'ж': 'zh',
      'з': 'z', 'и': 'i', 'й': 'y', 'к': 'k', 'л': 'l', 'м': 'm', 'н': 'n', 'о': 'o',
      'п': 'p', 'р': 'r', 'с': 's', 'т': 't', 'у': 'u', 'ф': 'f', 'х': 'kh', 'ц': 'ts',
      'ч': 'ch', 'ш': 'sh', 'щ': 'shch', 'ъ': '', 'ы': 'y', 'ь': "'", 'э': 'e', 'ю': 'yu', 'я': 'ya'
    };
    return html.replace(/>([^<]+)</g, (full, text) => {
      if (this.encoding === 'translit') {
        const converted = text.replace(/[а-яёА-ЯЁ]/g, ch => {
          const lower = ch.toLowerCase();
          const tr = mapTranslit[lower];
          if (tr === undefined) return ch;
          return ch === lower ? tr : tr.charAt(0).toUpperCase() + tr.slice(1);
        });
        return `>${converted}<`;
      }
      const koiSwap = text.replace(/[а-яёА-ЯЁ]/g, ch => {
        const code = ch.charCodeAt(0);
        if (code >= 1040 && code <= 1071) return String.fromCharCode(code + 32);
        if (code >= 1072 && code <= 1103) return String.fromCharCode(code - 32);
        return ch;
      });
      return `>${koiSwap}<`;
    });
  }

  playAnimalCall(soundType) {
    if (typeof window === 'undefined') return;
    if (window.soundSys && typeof window.soundSys.playDing === 'function') {
      window.soundSys.playDing();
    }
    try {
      const AudioCtx = window.AudioContext || window.webkitAudioContext;
      if (!AudioCtx) return;
      const ctx = new AudioCtx();
      const osc = ctx.createOscillator();
      const gain = ctx.createGain();
      osc.connect(gain);
      gain.connect(ctx.destination);
      const now = ctx.currentTime;
      if (soundType === 'tiger') {
        osc.type = 'sawtooth';
        osc.frequency.setValueAtTime(110, now);
        osc.frequency.exponentialRampToValueAtTime(62, now + 0.35);
      } else if (soundType === 'owl') {
        osc.type = 'sine';
        osc.frequency.setValueAtTime(290, now);
        osc.frequency.setValueAtTime(240, now + 0.18);
      } else if (soundType === 'nerpa' || soundType === 'aqua') {
        osc.type = 'sine';
        osc.frequency.setValueAtTime(660, now);
        osc.frequency.exponentialRampToValueAtTime(980, now + 0.25);
      } else {
        osc.type = 'triangle';
        osc.frequency.setValueAtTime(420, now);
        osc.frequency.exponentialRampToValueAtTime(520, now + 0.22);
      }
      gain.gain.setValueAtTime(0.08, now);
      gain.gain.exponentialRampToValueAtTime(0.001, now + 0.36);
      osc.start(now);
      osc.stop(now + 0.38);
    } catch (e) {}
  }

