  evaluateAquarium() {
    const liters = Number(this.aquaTankLiters) || 100;
    const temp = Number(this.aquaTempC) || 24;
    const filter = this.aquaFilterMode || 'airlift';
    const chosen = this.aquaFishCatalog.filter(f => this.aquaSelectedFish.includes(f.id));

    const totalCm = chosen.reduce((sum, f) => sum + f.cmTotal, 0);
    const filterFactor = filter === 'canister' ? 1.15 : (filter === 'airlift' ? 1.0 : 0.65);
    const maxSafeCm = Math.round((liters / 1.05) * filterFactor);
    const minRequiredTank = chosen.reduce((mx, f) => Math.max(mx, f.minTank), 15);

    const warnings = [];
    const dangers = [];
    const recovery = [];

    if (chosen.length === 0) {
      warnings.push('Аквариум пока заселён только водой и растениями — отметьте хотя бы один вид обитателей в списке выше.');
    }

    if (liters < minRequiredTank) {
      dangers.push(`Тесный объём: выбранным видам требуется аквариум минимум на ${minRequiredTank} л, а выбран сосуд на ${liters} л.`);
      recovery.push(`Увеличьте объём аквариума до ${minRequiredTank}–100 л или откажитесь от крупных рыб (скалярий / золотых рыбок).`);
    }

    if (totalCm > maxSafeCm) {
      dangers.push(`Перенаселение аквариума: суммарная длина рыб (${totalCm} см) превышает биологический предел (${maxSafeCm} см) для ${liters} л при текущей аэрации.`);
      recovery.push('Уменьшите число видов или установите полноценный эрлифтный фильтр с продувкой компрессором «Скалярия-М».');
    } else if (totalCm > Math.round(maxSafeCm * 0.8)) {
      warnings.push(`Плотная посадка (${totalCm} см из ${maxSafeCm} допустимых): потребуется еженедельная подмена 25% отстоянной воды.`);
    }

    if (filter === 'none' && chosen.length > 0) {
      warnings.push('Аквариум без компрессора и фильтрации рискует получить ночной кислородный замор.');
      recovery.push('Подключите мембранный компрессор «Скалярия-М» с распылителем и поролоновой губкой.');
    }

    chosen.forEach(f => {
      if (temp < f.minTemp || temp > f.maxTemp) {
        dangers.push(`Температурный конфликт для вида «${f.name}»: оптимум ${f.minTemp}..${f.maxTemp}°C, а терморегулятор выставлен на +${temp}°C.`);
        recovery.push(`Приведите температуру к диапазону ${f.minTemp}..${f.maxTemp}°C или отсадите холодноводных/теплолюбивых рыб в отдельный аквариум.`);
      }
    });

    const hasGoldfish = chosen.some(f => f.id === 'goldfish');
    const hasTropical = chosen.some(f => f.id === 'angelfish' || f.id === 'betta' || f.id === 'neon');
    if (hasGoldfish && hasTropical) {
      dangers.push('Несовместимость биотопов: холодноводная золотая рыбка (+17..+22°C, роет грунт) не уживается с тропическими скаляриями, петушками и неонами.');
      recovery.push('Содержите золотых рыбок в отдельном прохладном видовом аквариуме с крупной галькой.');
    }

    const hasBarb = chosen.some(f => f.finNipper);
    const hasLongFins = chosen.some(f => f.longFins);
    if (hasBarb && hasLongFins) {
      dangers.push('Конфликт поведения: суматранские барбусы обкусывают длинные вуалевые плавники у скалярий, гуппи, петушков и вуалехвостов!');
      recovery.push('Разделите суматранских барбусов и длинноплавничных рыб по разным аквариумам.');
    }

    const hasAngel = chosen.some(f => f.id === 'angelfish');
    const hasGuppy = chosen.some(f => f.id === 'guppy');
    if (hasAngel && hasGuppy) {
      warnings.push('Взрослые скалярии воспринимают мальков и мелких самцов гуппи как живой корм.');
    }

    let status = 'ok';
    let verdictTitle = 'ЭКОСИСТЕМА УСТОЙЧИВА • БАЛАНС ПО ЗОЛОТНИЦКОМУ СОБЛЮДЁН';
    if (dangers.length > 0) {
      status = 'danger';
      verdictTitle = 'ОПАСНОСТЬ ДЛЯ РЫБ • ОБНАРУЖЕНЫ БИОЛОГИЧЕСКИЕ КОНФЛИКТЫ!';
    } else if (warnings.length > 0) {
      status = 'warn';
      verdictTitle = 'ТРЕБУЕТСЯ ВНИМАНИЕ АКВАРИУМИСТА • ПОГРАНИЧНЫЙ РЕЖИМ';
    }

    if (recovery.length === 0) {
      recovery.push('Поддерживайте подмену 1/5 части отстоянной воды раз в 7 дней и давайте столько корма, сколько рыбы съедают за 4 минуты.');
    }

    return {
      liters,
      temp,
      filter,
      chosen,
      totalCm,
      maxSafeCm,
      status,
      verdictTitle,
      warnings,
      dangers,
      recovery
    };
  }

