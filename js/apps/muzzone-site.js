  calculateMp3(mins, bitrate, modem) {
    const m = Math.max(1, Math.min(300, Number(mins) || 45));
    const br = Number(bitrate) || 128;
    const md = Number(modem) || 33.6;
    const secs = m * 60;
    const sizeKb = Math.round((secs * br) / 8);
    const sizeMb = (sizeKb / 1024).toFixed(1);
    const realKbps = md * 0.72;
    const dlSecs = Math.round((sizeKb * 8) / realKbps);
    const dlMins = Math.max(1, Math.round(dlSecs / 60));
    const rioFits = Math.max(0, Math.floor((32 * 1024) / Math.max(1, sizeKb / Math.max(1, Math.round(m / 4)))));
    const cdrAlbums = Math.max(1, Math.floor(650 / Math.max(0.5, parseFloat(sizeMb))));
    return { mins: m, bitrate: br, modem: md, sizeMb, dlMins, rioFits, cdrAlbums };
  }

