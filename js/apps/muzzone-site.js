  encodeHtml(html) {
    if (this.encoding === 'win1251') return html;
    const trMap = {
      'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'е': 'e', 'ё': 'yo', 'ж': 'zh',
      'з': 'z', 'и': 'i', 'й': 'j', 'к': 'k', 'л': 'l', 'м': 'm', 'н': 'n', 'о': 'o',
      'п': 'p', 'р': 'r', 'с': 's', 'т': 't', 'у': 'u', 'ф': 'f', 'х': 'h', 'ц': 'c',
      'ч': 'ch', 'ш': 'sh', 'щ': 'sch', 'ъ': '', 'ы': 'y', 'ь': "'", 'э': 'e', 'ю': 'yu', 'я': 'ya'
    };
    const koiMap = {
      'а': 'А', 'б': 'Б', 'в': 'В', 'г': 'Г', 'д': 'Д', 'е': 'Е', 'ж': 'Ж', 'з': 'З',
      'и': 'И', 'й': 'Й', 'к': 'К', 'л': 'Л', 'м': 'М', 'н': 'Н', 'о': 'О', 'п': 'П',
      'р': 'Р', 'с': 'С', 'т': 'Т', 'у': 'У', 'ф': 'Ф', 'х': 'Х', 'ц': 'Ц', 'ч': 'Ч',
      'ш': 'Ш', 'щ': 'Щ', 'ы': 'Ы', 'э': 'Э', 'ю': 'Ю', 'я': 'Я'
    };
    return String(html).replace(/(<[^>]+>)|(&[a-zA-Z0-9#]+;)|([^<&]+)/g, (m, tag, ent, txt) => {
      if (tag || ent || !txt) return m;
      if (this.encoding === 'translit') {
        return txt.split('').map(ch => {
          const low = ch.toLowerCase();
          if (!Object.prototype.hasOwnProperty.call(trMap, low)) return ch;
          const out = trMap[low];
          return ch === low ? out : out.toUpperCase();
        }).join('');
      }
      if (this.encoding === 'koi8') {
        return txt.split('').map(ch => {
          const low = ch.toLowerCase();
          if (!Object.prototype.hasOwnProperty.call(koiMap, low)) return ch;
          return ch === low ? koiMap[low] : low;
        }).join('');
      }
      return txt;
    });
  }

  parseRoute(url = '') {
    const raw = String(url || this.baseUrl).trim();
    const qIdx = raw.indexOf('?');
    const pathPart = (qIdx >= 0 ? raw.slice(0, qIdx) : raw).toLowerCase();
    const queryStr = qIdx >= 0 ? raw.slice(qIdx + 1) : '';
    const params = {};
    if (queryStr) {
      queryStr.split('&').forEach(pair => {
        const eq = pair.indexOf('=');
        if (eq > 0) {
          const k = pair.slice(0, eq);
          let v = pair.slice(eq + 1).replace(/\+/g, ' ');
          try { v = decodeURIComponent(v); } catch (e) {}
          params[k] = v;
        }
      });
    }
    if (pathPart.endsWith('/article')) return { page: 'article', params };
    if (pathPart.endsWith('/news')) return { page: 'news', params };
    if (pathPart.endsWith('/clips')) return { page: 'clips', params };
    if (pathPart.endsWith('/clip')) return { page: 'clip', params };
    if (pathPart.endsWith('/charts')) return { page: 'charts', params };
    if (pathPart.endsWith('/reviews')) return { page: 'reviews', params };
    if (pathPart.endsWith('/tabs')) return { page: 'tabs', params };
    if (pathPart.endsWith('/forum')) return { page: 'forum', params };
    if (pathPart.endsWith('/search')) return { page: 'search', params };
    return { page: 'home', params };
  }

