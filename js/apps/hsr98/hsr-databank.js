  function isDocCollected(g, docId) {
    if (!g || !g.state || !g.state.flags) return false;
    return !!g.state.flags['doc_' + docId];
  }

  function seriesProgress(g, sr) {
    let got = 0, hasNew = false;
    const b = ensureBank(g);
    for (const v of sr.vols) {
      if (isDocCollected(g, v.id)) {
        got++;
        if (!b.booksSeen[v.id]) hasNew = true;
      }
    }
    return { got, total: sr.vols.length, hasNew };
  }

  function worldBookCounts(g, worldId) {
    sync(g);
    let got = 0, total = 0, hasNew = false;
    for (const sr of BOOK_SERIES) {
      if (worldId && sr.world !== worldId) continue;
      const p = seriesProgress(g, sr);
      got += p.got;
      total += p.total;
      if (p.hasNew) hasNew = true;
    }
    return { got, total, hasNew };
  }

  function foeGroup(id, d) {
    if (!d) return 'other';
    if (d.boss) return 'boss';
    if (/^(baryon|void_|blaze|frost|wind_sp|thunder_sp|trampler|grizzly_w)$/.test(id) || d.fam === 'legion') return 'legion';
    if (/^lf_|mara|sanctus|aurum|wolf_w|ape|ascend|ballist|hound|shape|twig|lotus/.test(id)) return 'luofu';
    if (/swarm|beetle|stinger/.test(id)) return 'swarm';
    if (/shadow_|toad|cabbage|dullahan|ethereal|hanuman|reaper/.test(id)) return 'interworld';
    if (/guard|automaton|hound_m|spider|beetle_m|vagrant|gepard|bronya|svarog|cocolia/.test(id)) return 'jarilo';
    return 'fragmentum';
  }

  function nodeCounts(g) {
    const b = sync(g), s = g && g.state ? g.state : { roster: {}, bank: b };
    const coneIds = Object.keys(H.CONES || {});
    const foeIds = Object.keys(H.ENEMIES || {});
    const charIds = Object.getOwnPropertyNames(H.CHARS || {});
    const relicSets = Object.keys(H.RELIC_SETS || {});
    const totalRelicPieces = relicSets.length * 4;
    let gotRelics = 0;
    for (const setId of relicSets) {
      for (const sl of ['head', 'hands', 'body', 'feet']) {
        if (b.relics[setId + ':' + sl]) gotRelics++;
      }
    }
    const secCount = list => {
      let got = 0, hasNew = false;
      for (const e of list) {
        if (isUnlocked(g, e)) {
          got++;
          if (!b.seen[e.id]) hasNew = true;
        }
      }
      return { got, total: list.length, hasNew };
    };
    const conesGot = coneIds.filter(id => b.cones[id]).length;
    const foesGot = foeIds.filter(id => b.enemies && b.enemies[id]).length;
    const charsGot = charIds.filter(id => s.roster && s.roster[id]).length;
    return {
      cones: { got: conesGot, total: coneIds.length, hasNew: coneIds.some(id => b.cones[id] && !b.seen['cone_' + id]) },
      foes: { got: foesGot, total: foeIds.length, hasNew: foeIds.some(id => b.enemies && b.enemies[id] && !b.seen['foe_' + id]) },
      factions: secCount(DB_FACTIONS),
      aeons: secCount(DB_AEONS),
      chars: { got: charsGot, total: charIds.length, hasNew: charIds.some(id => s.roster && s.roster[id] && !b.seen['char_' + id]) },
      relics: { got: gotRelics, total: totalRelicPieces, hasNew: relicSets.some(id => !b.seen['relic_' + id] && ['head', 'hands', 'body', 'feet'].some(sl => b.relics[id + ':' + sl])) },
      terms: secCount(DB_TERMS),
      books: worldBookCounts(g, null)
    };
  }

