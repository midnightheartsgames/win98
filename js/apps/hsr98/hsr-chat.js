    chatSync() {
      const cs = this.chats(), s = this.state, now = this.now(), fresh = [];
      const add = def => {
        const st = cs.th[def.id] = { at: now, k: ++cs.seq, n: 0, picks: [] };
        const old = def.mail && s.mail[def.mail];
        if (old && old.read) this.chatAuto(def.id, true);
        else fresh.push(def);
        return st;
      };
      for (const def of THREADS) {
        if (def.daily || cs.th[def.id] || !this.cond(def.need) || (def.lvl && s.roster.trail.lvl < def.lvl)) continue;
        const earlier = THREADS.slice(0, THREADS.indexOf(def)).filter(t => t.who === def.who && !t.daily);
        if (earlier.some(t => !cs.th[t.id] || !cs.th[t.id].done) || this.chatOpenFor(def.who)) continue;
        add(def);
      }
      const day = H.dayKey(now);
      if (cs.day !== day && s.flags.express_intro && !THREADS.some(t => t.daily && cs.th[t.id] && !cs.th[t.id].done)) {
        const def = THREADS.find(t => t.daily && !cs.th[t.id] && this.cond(t.need) && !this.chatOpenFor(t.who));
        if (def) { add(def); cs.day = day; }
      }
      if (fresh.length) this.emit({ t: 'chat', ids: fresh.map(d => d.id), who: fresh[fresh.length - 1].who });
      return fresh.map(d => d.id);
    },

    chatContacts() {
      const cs = this.chats(), out = new Map();
      for (const def of THREADS) {
        const st = cs.th[def.id];
        if (!st) continue;
        const c = out.get(def.who) || { who: def.who, threads: [], k: 0, open: false };
        c.threads.push(def.id);
        c.k = Math.max(c.k, st.k);
        if (!st.done) c.open = true;
        out.set(def.who, c);
      }
      for (const c of out.values()) c.threads.sort((a, b) => cs.th[a].k - cs.th[b].k);
      return [...out.values()].sort((a, b) => b.k - a.k);
    },

    chatCurrent(who) {
      const c = this.chatContacts().find(x => x.who === who);
      return c ? c.threads.find(id => !this.chatThread(id).done) || c.threads[c.threads.length - 1] : null;
    },

    chatNext(id) {
      const v = this.chatView(id);
      if (!v || !v.next) return null;
      const line = v.next;
      v.st.n++;
      if (line.quest && !this.state.quests[line.quest]) this.setQuest(line.quest, 'talk');
      if (line.give) this.give(line.give);
      const after = this.chatView(id);
      if (!after.next && !after.wait) v.st.done = true;
      return line;
    },

