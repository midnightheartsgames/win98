      hs.score += scoreGain;
      const scoreBonds = Math.floor(hs.score / HERTA_SCORE_STEP);
      hs.score %= HERTA_SCORE_STEP;
      let worldBonds = 0;
      if (win && su.world && !hs.worldBonds.includes(su.world)) {
        hs.worldBonds.push(su.world);
        worldBonds = 2;
      }
      const bonds = worldBonds + scoreBonds;
      if (bonds > 0) this.give({ items: { herta_bond: bonds } });
      return { scoreGain, scoreNow: hs.score, scoreCap: HERTA_SCORE_STEP, bonds, worldBonds, scoreBonds };
