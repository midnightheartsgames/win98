  function questList(g) {
    const out = [];
    for (const [id, st] of Object.entries(g.quests)) {
      const Q = QUESTS[id];
      if (!Q) continue;
      out.push({ id, title: Q.title, state: st, main: !!Q.main, objectives: st === 'active' ? Q.objectives(g) : [] });
    }
    out.sort((a, b) => (b.main - a.main) || ((a.state === 'active' ? 0 : 1) - (b.state === 'active' ? 0 : 1)));
    return out;
  }

