  const parseUrl = (url) => {
    const raw = String(url || '');
    const hashAt = raw.indexOf('#');
    const anchor = hashAt >= 0 ? raw.slice(hashAt + 1) : '';
    const bare = hashAt >= 0 ? raw.slice(0, hashAt) : raw;
    const parts = bare.match(/^(?:[a-z]+:\/\/)?([^/?]*)([^?]*)(?:\?(.*))?$/i) || [];
    const path = (parts[2] || '').toLowerCase().replace(/\/+$/, '');
    const query = {};
    (parts[3] || '').split('&').forEach(pair => {
      const [k, v = ''] = pair.split('=');
      if (!k) return;
      try { query[k.toLowerCase()] = decodeURIComponent(v); } catch (e) { query[k.toLowerCase()] = v; }
    });
    const num = parseInt(query.id, 10);
    if (path === '/thread') return { view: 'thread', id: Number.isFinite(num) ? num : null, anchor };
    if (path === '/post') return { view: 'post', forum: forumOf(query.forum) ? query.forum : 'hall' };
    if (path === '/forum') return forumOf(query.id) ? { view: 'forum', forum: query.id } : { view: 'missing' };
    if (path === '' || path === '/index.html') return { view: 'index' };
    return { view: 'missing' };
  };

