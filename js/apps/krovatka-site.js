  getRoomMessages(room) {
    const roomObj = this.getRoom(room);
    try {
      if (typeof localStorage !== 'undefined') {
        const data = localStorage.getItem(`${this.chatMessagesKey}_${roomObj.id}`);
        if (data) {
          const parsed = JSON.parse(data);
          if (Array.isArray(parsed) && parsed.length > 0) return parsed;
        }
      }
    } catch (e) {}
    const seed = this.DEFAULT_MESSAGES[roomObj.id] || this.DEFAULT_MESSAGES.general;
    return seed.map(m => ({ ...m }));
  }

  saveRoomMessages(room, msgs) {
    const roomObj = this.getRoom(room);
    try {
      if (typeof localStorage !== 'undefined') {
        localStorage.setItem(`${this.chatMessagesKey}_${roomObj.id}`, JSON.stringify(msgs));
      }
    } catch (e) {}
  }

  resetRoomMessages(room) {
    const roomObj = this.getRoom(room);
    try {
      if (typeof localStorage !== 'undefined') {
        localStorage.removeItem(`${this.chatMessagesKey}_${roomObj.id}`);
      }
    } catch (e) {}
    return this.getRoomMessages(roomObj.id);
  }

  stepRoomBeat(room) {
    const roomObj = this.getRoom(room);
    const beats = this.ROOM_BEATS[roomObj.id] || this.ROOM_BEATS.general;
    let map = {};
    try {
      if (typeof localStorage !== 'undefined') {
        map = JSON.parse(localStorage.getItem(this.beatIndexKey)) || {};
      }
    } catch (e) {}
    const idx = (map[roomObj.id] || 0) % beats.length;
    const beat = beats[idx];
    map[roomObj.id] = idx + 1;
    try {
      if (typeof localStorage !== 'undefined') {
        localStorage.setItem(this.beatIndexKey, JSON.stringify(map));
      }
    } catch (e) {}

    const now = new Date();
    const timeStr = beat.time || `${String(now.getHours()).padStart(2, '0')}:${String(now.getMinutes()).padStart(2, '0')}`;
    const msgs = this.getRoomMessages(roomObj.id);
    const entry = {
      user: beat.user,
      color: beat.color || '#000080',
      time: timeStr,
      text: beat.text
    };
    msgs.push(entry);
    this.saveRoomMessages(roomObj.id, msgs);
    return entry;
  }

