  writeArtifactToVfs(fileName, content, openNotepad = true) {
    const folder = ['My Computer', 'C:', 'My Documents'];
    if (typeof window !== 'undefined' && window.vfs) {
      if (typeof window.vfs.mkdir === 'function') {
        try { window.vfs.mkdir(['My Computer', 'C:'], 'My Documents'); } catch (e) {}
      }
      if (typeof window.vfs.writeFile === 'function') {
        window.vfs.writeFile(folder, fileName, content);
      } else if (typeof window.vfs.createFile === 'function') {
        window.vfs.createFile(folder, fileName, content);
      }
    }
    if (openNotepad && typeof window !== 'undefined' && window.appNotepad) {
      if (typeof window.appNotepad.open === 'function') {
        window.appNotepad.open(fileName, content);
      } else if (typeof window.appNotepad.openWithContent === 'function') {
        window.appNotepad.openWithContent(fileName, content);
      }
    }
    return fileName;
  }

