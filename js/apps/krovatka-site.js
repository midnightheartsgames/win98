  esc(val) {
    return String(val == null ? '' : val)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
  }

  gif(name, scale = 1, title = '') {
    return typeof window !== 'undefined' && typeof window.webGif === 'function'
      ? window.webGif(name, scale, title)
      : '';
  }

  mailLink(address, label) {
    if (typeof window !== 'undefined' && window.appIE && typeof window.appIE.mailLink === 'function') {
      return window.appIE.mailLink(address, label);
    }
    const text = label || address;
    return `<a href="mailto:${this.esc(address)}">${this.esc(text)}</a>`;
  }

