  function simplify(pts, tol) {
    if (!tol || pts.length < 3) return pts.slice();
    const keep = new Array(pts.length).fill(false);
    keep[0] = keep[pts.length - 1] = true;
    const stack = [[0, pts.length - 1]];
    while (stack.length) {
      const [i0, i1] = stack.pop();
      const a = pts[i0], c = pts[i1], dx = c[0] - a[0], dy = c[1] - a[1], len = Math.hypot(dx, dy) || 1;
      let best = -1, far = tol;
      for (let i = i0 + 1; i < i1; i++) {
        const d = Math.abs((pts[i][0] - a[0]) * dy - (pts[i][1] - a[1]) * dx) / len;
        if (d > far) { far = d; best = i; }
      }
      if (best > 0) { keep[best] = true; stack.push([i0, best], [best, i1]); }
    }
    return pts.filter((_, i) => keep[i]);
  }

